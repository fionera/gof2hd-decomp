"""Generate src/engine/render/LowResourceTable.cpp (loadLowTexturesAndMaterials) from the
ORIGINAL binary: a straight-line list of canvas->AddResource(new Resource(...)) calls.

  python3 _work/reconstructions/gameresource_gen/gen_low.py > src/engine/render/LowResourceTable.cpp
"""
import sys
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from extract import extract  # noqa
from emit import entry_expr, HEADER_INCLUDES  # noqa

FN = '_Z27loadLowTexturesAndMaterialsPN11AbyssEngine6EngineE'


def main():
    out, _ = extract(FN)
    adds = [r for r in out if r['t'] == 'add']
    calls = [r for r in out if r['t'] == 'call' and r['name'] not in ('_ZdlPv', '_Unwind_Resume')]
    assert not calls, calls
    o = [HEADER_INCLUDES.replace('#include "game/core/Globals.h"', '').rstrip(), '',
         '// Generated by _work/reconstructions/gameresource_gen/gen_low.py from the original binary.',
         'void loadLowTexturesAndMaterials(AbyssEngine::Engine *engine) {',
         '    using namespace AbyssEngine;',
         '    PaintCanvas *canvas = engine->appManager->paintCanvas;',
         '']
    for r in adds:
        rec = (r['id'].v, r['rkind'].v, r['unused'].v, r['payload'])
        o.append('    canvas->AddResource(%s);' % entry_expr(rec))
    o.append('}')
    print('\n'.join(o))


if __name__ == '__main__':
    main()
