"""Generate src/engine/render/BuildResourceList.cpp from the ORIGINAL binary.

  python3 _work/reconstructions/gameresource_gen/gen_brl.py > src/engine/render/BuildResourceList.cpp

The 2488-entry resource table and the device-dependent tail are recovered entry by entry
from the original BuildResourceList's machine code (armdis.Interp symbolic execution; strings
from .rodata through the literal pools). The tail's if/else structure was recovered with
paths.py (every Globals flag assignment executed) and is verified here: the generated
structure is re-simulated for all 16 flag assignments and must reproduce the original's
AddResource sequence exactly.
"""
import sys
import itertools
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from extract import extract  # noqa
from paths import run_paths  # noqa
from emit import entry_expr, HEADER_INCLUDES  # noqa

FN = '_Z17BuildResourceListPN11AbyssEngine6EngineE'
HD, IPAD, RETINA, LARGE = ('_ZN7Globals6iPadHDE', '_ZN7Globals4iPadE',
                           '_ZN7Globals13retinaDisplayE', '_ZN7Globals9iPadLargeE')
FLAGS = [HD, IPAD, RETINA, LARGE]
CNAME = {HD: 'Globals::iPadHD', IPAD: 'Globals::iPad', RETINA: 'Globals::retinaDisplay',
         LARGE: 'Globals::iPadLarge'}


def rec_of(r):
    return (r['id'].v, r['rkind'].v, r['unused'].v, r['payload'])


def main():
    out, _ = extract(FN)
    slots = [r for r in out if r['t'] == 'slot']
    assert [r['off'] for r in slots] == [788 + 4 * k for k in range(len(slots))]
    table = [rec_of(r) for r in slots]

    P = run_paths(FN, 0x10a25a, 0x10edc2, FLAGS)

    def p(hd, ipad, retina, large):
        return P[(hd, ipad, retina, large)]

    def tex_index(seq, name):
        for k, r in enumerate(seq):
            if r[3][0] == 'tex' and r[3][1].endswith('/' + name):
                return k
        raise KeyError(name)

    def first_image(seq):
        for k, r in enumerate(seq):
            if r[3][0] == 'image':
                return k
        raise KeyError

    base = p(0, 0, 0, 0)
    c0 = tex_index(base, 'planet_000_small.aei')
    common = base[c0:]
    nb = tex_index(base, 'gof2_dlc_interface.aei')
    b_notipad = base[nb:c0]
    a_plain_head = base[:9]
    a_plain_notipad = base[9:nb]
    hd = p(1, 0, 0, 0)
    a_hd = hd[:tex_index(hd, 'gof2_dlc_interface.aei')]
    r0 = p(0, 0, 1, 0)
    a_ret_head = r0[:9]
    a_ret_notlarge = r0[9:tex_index(r0, 'gof2_dlc_interface.aei')]
    ip = p(0, 1, 0, 0)
    fi = first_image(ip)
    ci = tex_index(ip, 'planet_000_small.aei')
    b_ipad_images = ip[fi:ci]
    b_ipad_plain = ip[9:fi]
    ipr = p(0, 1, 1, 1)
    b_ipad_retina = ipr[9:first_image(ipr)]
    iphd = p(1, 1, 0, 0)
    b_ipad_hd = iphd[len(a_hd):first_image(iphd)]

    # The structure (also what the source below spells out):
    def simulate(f):
        s = []
        if f[HD]:
            s += a_hd
        elif f[RETINA]:
            s += a_ret_head
            if not f[LARGE]:
                s += a_ret_notlarge
        else:
            s += a_plain_head
            if not f[IPAD]:
                s += a_plain_notipad
        if f[IPAD]:
            if f[RETINA]:
                s += b_ipad_retina
            elif f[HD]:
                s += b_ipad_hd
            else:
                s += b_ipad_plain
            s += b_ipad_images
        else:
            s += b_notipad
        s += common
        return s

    for vals in itertools.product([0, 1], repeat=4):
        f = dict(zip(FLAGS, vals))
        assert simulate(f) == P[vals], vals

    # the 152-entry loop, read off the original loop body
    o = []
    w = o.append
    w(HEADER_INCLUDES)
    w('')
    w('void loadPortraits(AbyssEngine::Engine *engine);')
    w('void loadLowTexturesAndMaterials(AbyssEngine::Engine *engine);')
    w('')
    w('// Generated by _work/reconstructions/gameresource_gen/gen_brl.py from the original binary.')
    w('void BuildResourceList(AbyssEngine::Engine *engine) {')
    w('    using namespace AbyssEngine;')
    w('    engine->appManager->paintCanvas->TextureCreateGlobal(')
    w('        String("data/assets/main/3d/textures/low/etc/fx/cloak_map.aei"), 6);')
    w('')
    w('    Resource *resources[%d];' % len(table))
    for k, r in enumerate(table):
        w('    resources[%d] = %s;' % (k, entry_expr(r)))
    w('    engine->appManager->paintCanvas->SetResourceList(resources, %d);' % len(table))
    w('')
    w('    PaintCanvas *canvas = engine->appManager->paintCanvas;')
    w('    for (int i = 0; i < 152; ++i)')
    w('        canvas->AddResource(new Resource(5000 + i, RESOURCE_IMAGE, new ResourceImage(10200 + i, 0)));')
    w('')

    def block(seq, ind):
        for r in seq:
            w(' ' * ind + 'canvas->AddResource(%s);' % entry_expr(r))

    w('    if (%s) {' % CNAME[HD])
    block(a_hd, 8)
    w('    } else if (%s) {' % CNAME[RETINA])
    block(a_ret_head, 8)
    w('        if (!%s) {' % CNAME[LARGE])
    block(a_ret_notlarge, 12)
    w('        }')
    w('    } else {')
    block(a_plain_head, 8)
    w('        if (!%s) {' % CNAME[IPAD])
    block(a_plain_notipad, 12)
    w('        }')
    w('    }')
    w('')
    w('    if (%s) {' % CNAME[IPAD])
    w('        if (%s) {' % CNAME[RETINA])
    block(b_ipad_retina, 12)
    w('        } else if (%s) {' % CNAME[HD])
    block(b_ipad_hd, 12)
    w('        } else {')
    block(b_ipad_plain, 12)
    w('        }')
    block(b_ipad_images, 8)
    w('    } else {')
    block(b_notipad, 8)
    w('    }')
    w('')
    block(common, 4)
    w('')
    w('    loadPortraits(engine);')
    w('    loadLowTexturesAndMaterials(engine);')
    w('}')
    print('\n'.join(o))


if __name__ == '__main__':
    main()
